class OutputStage:
    """
    Stage 5: Generate final HTML output.

    - Converts rewritten content to HTML
    - Applies template
    - Saves to file system
    """

    def __init__(
        self,
        db: Database,
        openai: OpenAIClient,
        file_store: FileStore,
        progress: ProgressTracker,
    ):
        self.db = db
        self.openai = openai
        self.file_store = file_store
        self.progress = progress

    async def process(self, batch_id: str, guide_ids: list[str]) -> list[str]:
        """
        Generate HTML for each guide.

        Args:
            batch_id: The batch ID
            guide_ids: List of guide IDs to process

        Returns:
            List of successfully generated guide IDs
        """
        await self.progress.start_stage(PipelineStage.GENERATING, len(guide_ids))

        if not guide_ids:
            logger.warning("No guides to generate")
            return []

        successful_ids = []
        processed = 0
        failed = 0

        for guide_id in guide_ids:
            guide = await self.db.get_guide(guide_id)
            if not guide:
                logger.warning(f"Guide not found: {guide_id}")
                failed += 1
                continue

            title = guide["title"]
            description = guide.get("description", "")
            slug = guide["slug"]
            rewritten_content = guide.get("rewritten_content", "")

            try:
                await self.progress.update_item_progress(
                    processed=processed,
                    failed=failed,
                    current_file=title,
                    message=f"Generating HTML: {title}...",
                )

                if not rewritten_content:
                    logger.warning(f"No content for guide: {title}")
                    failed += 1
                    continue

                # Convert to HTML using OpenAI
                html_content = await self.openai.generate_html(
                    markdown_content=rewritten_content,
                    title=title,
                    description=description,
                )

                # Apply template
                full_html = DEFAULT_TEMPLATE.format(
                    title=title,
                    description=description,
                    content=html_content,
                )

                # Store HTML file
                output_path = await self.file_store.store_output(
                    batch_id=batch_id,
                    slug=slug,
                    html_content=full_html,
                )

                # Update guide record
                await self.db.update_guide(
                    guide_id=guide_id,
                    html_path=str(output_path),
                    status="completed",
                )

                successful_ids.append(guide_id)
                processed += 1

                await self.progress.update_item_progress(
                    processed=processed,
                    failed=failed,
                    message=f"Generated: {title}",
                )

                logger.info(f"Successfully generated HTML: {title}")

            except OpenAIError as e:
                logger.error(f"OpenAI error generating {title}: {e}")
                await self.db.update_guide(guide_id=guide_id, status="failed")
                failed += 1

                await self.progress.update_item_progress(
                    processed=processed,
                    failed=failed,
                    message=f"Failed: {title}",
                )

            except Exception as e:
                logger.error(f"Unexpected error generating {title}: {e}")
                await self.db.update_guide(guide_id=guide_id, status="failed")
                failed += 1

                await self.progress.update_item_progress(
                    processed=processed,
                    failed=failed,
                    message=f"Error: {title}",
                )

        logger.info(
            f"Output stage complete: {len(successful_ids)} generated, {failed} failed"
        )
        return successful_ids
